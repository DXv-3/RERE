// @effect-diagnostics nodeBuiltinImport:off - A build-time generator that reads Playwright's Node bundle.
/**
 * Writes Playwright's injected selector engine into the phone app as a string, so the phone's
 * browser resolves `role=…` and `text=…` locators exactly as the desktop does. The phone cannot read
 * `playwright-core` at run time, so the source is generated here and committed. Run it after
 * updating playwright-core in apps/desktop:
 *
 *   node scripts/generate-mobile-playwright-runtime.ts
 */
import * as NodeFS from "node:fs";
import * as NodeModule from "node:module";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";
import * as NodeVM from "node:vm";

const repo = NodePath.resolve(NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)), "..");
const desktopRequire = NodeModule.createRequire(NodePath.join(repo, "apps/desktop/package.json"));
const packageJsonPath = desktopRequire.resolve("playwright-core/package.json");
const version = (JSON.parse(NodeFS.readFileSync(packageJsonPath, "utf8")) as { version: string })
  .version;
const bundle = NodeFS.readFileSync(
  NodePath.join(NodePath.dirname(packageJsonPath), "lib/coreBundle.js"),
  "utf8",
);
// Same markers as apps/desktop/src/preview/PlaywrightInjectedRuntime.ts.
const marker = "source3 = ";
const terminator = ";\n  }\n});";
const start = bundle.indexOf(marker);
const end = bundle.indexOf(terminator, start);
if (start < 0 || end < 0)
  throw new Error(`Playwright ${version}: injected source markers not found.`);
const source: unknown = NodeVM.runInNewContext(
  bundle.slice(start + marker.length, end),
  Object.create(null),
  { timeout: 1_000 },
);
if (typeof source !== "string" || source.length < 100_000) {
  throw new Error(`Playwright ${version}: injected source is not the expected string.`);
}
const output = NodePath.join(
  repo,
  "apps/mobile/src/features/browser/playwrightInjectedSource.generated.ts",
);
NodeFS.writeFileSync(
  output,
  `// Generated by scripts/generate-mobile-playwright-runtime.ts from playwright-core ${version}. Do not edit.\n` +
    `export const PLAYWRIGHT_CORE_VERSION = ${JSON.stringify(version)};\n` +
    `export const PLAYWRIGHT_INJECTED_SOURCE = ${JSON.stringify(source)};\n`,
);
process.stdout.write(
  `wrote ${NodePath.relative(repo, output)} (${source.length} characters, playwright-core ${version})\n`,
);
